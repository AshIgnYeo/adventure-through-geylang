// Writes src/builder-registry.ts from src/builder-owners.mjs: the building-id lookup and an on-demand loader for each
// builder module. Run with `npm run registry`; dev and build run it first. The registry test fails when the
// committed file is stale.
import fs from 'node:fs';
import { builderOwners, builderIndex } from '../src/builder-owners.mjs';

export const registryPath = new URL('../src/builder-registry.ts', import.meta.url);

export function renderRegistry(owners = builderOwners) {
  const { shared } = builderIndex(owners);
  if (shared.size) throw new Error(`Buildings claimed by more than one module: ${[...shared].map(([id, m]) => `${id} (${m.join(', ')})`).join('; ')}`);
  const entries = owners.map(({ module, build, ids }) =>
    `  ['${module}', () => import('./${module}').then(m => m.${build}), ${JSON.stringify([...new Set(ids)])}],`);
  return [
    '// Generated by scripts/build-registry.mjs from src/builder-owners.mjs. Do not edit; run `npm run registry`.',
    "import type { World, Point } from './world';",
    '',
    '/** Models one building on its footprint. Returns false when the building is not its own. */',
    'export type Builder = (world: World, id: string, poly: Point[]) => boolean;',
    '',
    'const entries: [string, () => Promise<Builder>, string[]][] = [',
    ...entries,
    '];',
    '',
    '/** Building id to its builder module, and each module\'s loader. Modules load only when a building needs them. */',
    'export const builderModule = new Map<string, string>(entries.flatMap(([module, , ids]) => ids.map(id => [id, module] as [string, string])));',
    'export const loadBuilder = new Map<string, () => Promise<Builder>>(entries.map(([module, load]) => [module, load]));',
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = renderRegistry();
  const current = fs.existsSync(registryPath) ? fs.readFileSync(registryPath, 'utf8') : '';
  if (text !== current) fs.writeFileSync(registryPath, text);
  console.log(`builder registry: ${builderOwners.length} modules, ${new Set(builderOwners.flatMap(o => o.ids)).size} buildings${text === current ? '' : ' (updated)'}`);
}
